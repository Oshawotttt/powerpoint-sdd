#!/bin/sh
# Combine a deck's spec into one file: <spec folder>/FULL.md.
# Usage: combine.sh [spec folder]   (default: current directory)
# Writes ARCHITECTURE.md, then every [0-9][0-9]-*.md section file in file-name order.

dir=${1:-.}
out="$dir/FULL.md"

if [ ! -f "$dir/ARCHITECTURE.md" ]; then
    echo "ARCHITECTURE.md not found in $dir" >&2
    exit 1
fi

LC_ALL=C
export LC_ALL

{
    echo '<!-- Generated by /ppt-combine. Do not edit: edit ARCHITECTURE.md and the section files. -->'
    echo
    cat "$dir/ARCHITECTURE.md"
    for f in "$dir"/[0-9][0-9]-*.md; do
        [ -f "$f" ] || continue
        printf '\n---\n\n'
        cat "$f"
    done
} > "$out" || exit 1

echo "$out"
